def route_costs(lazy):
    """(cost, length, nodes) of the engine search between a few chart pairs, region off."""
    out = []
    for a, b in ((0, -1), (1, -2), (0, len(lazy.keys) // 2)):
        r = lazy.route(lazy.keys[a], lazy.keys[b])
        out.append(None if r is None else (int(r.cost), round(float(r.length), 4), len(r.nodes)))
    return out


@pytest.mark.parametrize("variant", sorted(VARIANTS))
def test_region_off_plans_equal_the_golden_values(world, variant):
    name, eng, lazy = world
    got = [digest(_plan(lazy, p, q, **VARIANTS[variant])) for p, q in _trial_pairs(eng, 4, 11)]
    assert all(not g["region_key"] and g["cost_model"] is None for g in got)
    assert got == GOLDEN[(name, variant)]
    assert any("nodes" in g and len(g["nodes"]) >= 2 for g in got)


def test_region_off_engine_costs_equal_the_golden_values(world):
    name, eng, lazy = world
    assert route_costs(lazy) == GOLDEN[(name, "engine")]
