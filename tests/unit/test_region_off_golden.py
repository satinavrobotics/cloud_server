def _plan(graph, p, q, kappa, turn):
    ids = iter("n%d" % i for i in range(10 ** 5))
    seen = {}
    try:
        return sr.plan_on_graph(graph, "m", p, q, ([], []), lambda x, y: seen.setdefault((round(x, 3), round(y, 3)), next(ids)),
                                0.5, 1.5, 3.0, None, 0.05, None, None, kappa, True, 400, turn=turn,
                                region=None, region_mode="off")
    except sr.ChartFallback as err:
        return err.reason


def digest(plan) -> dict:
    """Route nodes, cost and a digest of everything the route node carries (like `route_digest`: no
    recording data)."""
    if isinstance(plan, str):
        return {"fallback": plan}
    wps = [{k: v for k, v in w.dict().items() if v is not None and k != "chart_key"} for w in plan.waypoints]
    body = {"waypoints": wps, "path": plan.planned_path, "trajectory": plan.trajectory, "node_policy": plan.node_policy,
            "min_width": plan.min_width, "charts": list(plan.charts)}
    h = hashlib.sha1(json.dumps(body, sort_keys=True, default=str).encode()).hexdigest()[:16]
    return {"nodes": [(round(w.x, 4), round(w.y, 4)) for w in plan.waypoints], "cost": plan.pricing and plan.pricing["cost"],
            "region_key": bool(plan.pricing and "region" in plan.pricing), "cost_model": plan.cost_model, "digest": h}


